const digest = (() => {
  const hash = createHash("sha256")
  for (const name of contractInputs) {
    hash.update(name)
    hash.update(Buffer.from([0]))
    hash.update(input(name))
    hash.update(Buffer.from([0]))
  }
  return hash.digest("hex")
})()

