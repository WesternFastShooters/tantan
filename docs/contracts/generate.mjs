const prettierConfig = (await resolveConfig(resolve(repositoryRoot, "package.json"))) ?? {}
const formatGo = (source) => execFileSync("gofmt", [], { input: source })
const formatTypeScript = async (source) =>
  Buffer.from(await format(source, { ...prettierConfig, parser: "typescript" }))

const outputs = new Map([
  ["services/tantan-api/internal/api/gen/types.go", formatGo(goTypes)],
  ["apps/desktop/layer/renderer/src/lib/tantan-api/gen/types.ts", await formatTypeScript(tsTypes)],
  ["services/tantan-api/internal/ai/schema/embed.go", formatGo(embeddedSchemas)],
  ["docs/contracts/contract.sha256", Buffer.from(`${digest}\n`)],
])

for (const name of contractInputs.filter((name) => name.startsWith("spec-package/schemas/"))) {
  outputs.set(`services/tantan-api/internal/ai/schema/${name.split("/").at(-1)}`, input(name))
}

for (const name of contractInputs.filter((name) => name.startsWith("spec-package/db/"))) {
  outputs.set(`services/tantan-api/migrations/${name.split("/").at(-1)}`, input(name))
}

const mismatches = []
for (const [name, contents] of outputs) {
  const target = resolve(repositoryRoot, name)
  if (checkOnly) {
    if (!existsSync(target) || !readFileSync(target).equals(contents)) {
      mismatches.push(name)
    }
    continue
  }
  mkdirSync(dirname(target), { recursive: true })
  if (!existsSync(target) || !readFileSync(target).equals(contents)) {
    writeFileSync(target, contents)
  }
}

if (checkOnly && mismatches.length > 0) {
  for (const name of mismatches) {
    process.stderr.write(`generated contract differs: ${name}\n`)
  }
  process.exitCode = 1
} else {
  process.stdout.write(`${checkOnly ? "verified" : "generated"} contract ${digest}\n`)
}
